const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { createRequire } = require('node:module')
const { promisify } = require('node:util')
const run = promisify(require('node:child_process').execFile)
const { score } = require('./Score-WordReview.cjs')
const { loadDataset } = require('./New-WordReview.cjs')
const uiRequire = createRequire(path.join(__dirname, '../src/ShortForge.Ui/package.json'))
const { chromium } = uiRequire('playwright')

async function main() {
  const [sample, srt, sheet] = process.argv.slice(2)
  if (!sheet) throw new Error('Pass the sample directory, source SRT and generated index.html.')
  const data = loadDataset(sample,srt)
  const empty = {version:1, batchId:data.batchId, rows:data.targets.map(t=>({cue:t.cue,status:'pending',onsetMs:null}))}
  assert.equal(score(data,empty).meetsSampleGoal,null)
  assert.throws(()=>score(data,{...empty,batchId:'other'}))
  assert.throws(()=>score(data,{...empty,rows:empty.rows.slice(1)}))
  const testRows = data.targets.map(t=>({cue:t.cue,status:'marked',onsetMs:t.asrMs}))
  assert.equal(score(data,{...empty,rows:testRows}).meetsSampleGoal,true)
  const duplicate=testRows.slice()
  duplicate[1]=duplicate[0]
  assert.throws(()=>score(data,{...empty,rows:duplicate}))
  assert.throws(()=>score(data,{...empty,rows:[{...testRows[0],onsetMs:data.targets[0].endMs},...testRows.slice(1)]}))
  const shifted = testRows.map((row,i)=>{
    const t=data.targets[i]
    const delta=i<3?251:250
    return {...row,onsetMs:row.onsetMs+(row.onsetMs+delta<t.endMs ? delta : -delta)}
  })
  const measured = score(data,{...empty,rows:shifted})
  assert.equal(measured.within250ms,23)
  assert.equal(measured.medianAbsoluteMs,250)
  assert.equal(measured.meetsSampleGoal,false)
  const tmp=await fs.mkdtemp(path.join(os.tmpdir(),'ShortForge-word-review-'))
  const browser=await chromium.launch({channel:'msedge',headless:true})
  try {
    const context=await browser.newContext({acceptDownloads:true,viewport:{width:1024,height:680}})
    const page=await context.newPage()
    const errors=[], external=[]
    page.on('pageerror',e=>errors.push(e.message))
    await context.route(/^https?:/i,route=>{external.push(route.request().url());return route.abort()})
    await page.goto(pathToFileURL(path.resolve(sheet)).href)
    const select=page.locator('#target'), wave=page.locator('#wave'), mark=page.locator('#mark')
    assert.equal(await select.locator('option').count(),data.targets.length)
    assert.equal(await mark.isDisabled(),true)
    const first=data.targets[0]
    assert.equal(await page.locator('#word').textContent(),first.word)
    await page.locator('#audio').evaluate(async el=>{ await el.play(); if(!(el.duration>0)) throw Error('No audio'); el.pause() })
    await wave.scrollIntoViewIfNeeded()
    await wave.click({position:{x:55,y:20}})
    await page.locator('#plus').click()
    await page.locator('#play-around').click()
    await page.waitForFunction(()=>!document.querySelector('#audio').paused)
    await page.waitForFunction(()=>document.querySelector('#audio').paused)
    await mark.click()
    const second=data.targets[1]
    await select.selectOption(String(second.cue))
    await page.locator('#skip').click()
    async function download(file) {
      const download=page.waitForEvent('download')
      await page.locator('#save').click()
      await (await download).saveAs(file)
      return JSON.parse(await fs.readFile(file,'utf8'))
    }
    const manual=path.join(tmp,'manual.json')
    const saved=await download(manual)
    let report=score(data,saved)
    assert.equal(report.marked,1)
    assert.equal(report.skipped,1)
    assert.equal(report.meetsSampleGoal,null)
    assert.equal(saved.rows.find(r=>r.cue===first.cue).status,'marked')
    await page.reload()
    const resumed=await download(path.join(tmp,'resumed.json'))
    assert.deepEqual(resumed.rows,saved.rows)
    const output=path.join(tmp,'result.json')
    const args=[path.join(__dirname,'Score-WordReview.cjs'),sample,srt,manual,output]
    await run(process.execPath,args)
    assert.deepEqual(JSON.parse(await fs.readFile(output,'utf8')),report)
    await assert.rejects(run(process.execPath,args))
    assert.deepEqual(JSON.parse(await fs.readFile(output,'utf8')),report)
    await select.selectOption(String(first.cue))
    await page.locator('#clear').click()
    report=score(data,await download(path.join(tmp,'cleared.json')))
    assert.equal(report.marked,0)
    assert.equal(report.skipped,1)
    const fileInput=page.locator('#import')
    await fileInput.setInputFiles(manual)
    await page.waitForFunction(()=>document.querySelector('#import').value==='')
    assert.deepEqual((await download(path.join(tmp,'imported.json'))).rows,saved.rows)
    await fileInput.setInputFiles({name:'other.json',mimeType:'application/json',
      buffer:Buffer.from(JSON.stringify({...saved,batchId:'other'}))})
    await page.waitForFunction(()=>document.querySelector('#storage').textContent.includes('Не удалось загрузить'))
    assert.deepEqual((await download(path.join(tmp,'after-rejection.json'))).rows,saved.rows)
    assert.deepEqual(external,[])
    assert.deepEqual(errors,[])
    console.log('PASS: real WAV playback, blind selection, replay, mark/skip, draft reload and export, clear, range and identity validation, ±250 ms threshold and overwrite protection; zero external requests.')
  } finally {
    await browser.close()
    await fs.rm(tmp,{recursive:true,force:true})
  }
}
main().catch(error=>{console.error(error);process.exitCode=1})
